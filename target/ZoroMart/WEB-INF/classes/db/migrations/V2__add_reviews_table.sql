CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL, user_id BIGINT NOT NULL, order_id BIGINT NOT NULL, rating INT NOT NULL CHECK(rating BETWEEN 1 AND 5), comment VARCHAR(1000), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_review_order_product UNIQUE(order_id,product_id), CONSTRAINT fk_review_product FOREIGN KEY(product_id) REFERENCES products(id),
 CONSTRAINT fk_review_user FOREIGN KEY(user_id) REFERENCES users(id), CONSTRAINT fk_review_order FOREIGN KEY(order_id) REFERENCES orders(id)
);
CREATE INDEX IF NOT EXISTS idx_reviews_product ON reviews(product_id); CREATE INDEX IF NOT EXISTS idx_reviews_user ON reviews(user_id);

